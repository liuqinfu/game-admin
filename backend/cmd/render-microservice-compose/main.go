func renderLoggedCommand(serviceName, target string) string {
	return fmt.Sprintf("[\"bash\", \"-lc\", \"mkdir -p /app/deploy/observability/logs && exec > >(tee -a /app/deploy/observability/logs/%s.log) 2>&1; go run %s\"]", serviceName, target)
}

func gatewayEnvKey(serviceName string) string {
	switch strings.TrimSpace(serviceName) {
	case "data-platform-sync-service":
		return "DATA_SYNC"
	default:
		return strings.ToUpper(strings.ReplaceAll(strings.TrimSuffix(serviceName, "-service"), "-", "_"))
	}
}
