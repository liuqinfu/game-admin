package main

import (
	"fmt"
	"os"
	"slices"
	"strings"

	"game-admin/backend/internal/servicedef"
)

func main() {
	out := os.Stdout
	if len(os.Args) > 1 && strings.TrimSpace(os.Args[1]) != "" {
		file, err := os.Create(strings.TrimSpace(os.Args[1]))
		if err != nil {
			fmt.Fprintf(os.Stderr, "create output file: %v\n", err)
			os.Exit(1)
		}
		defer file.Close()
		out = file
	}

	fmt.Fprint(out, renderCompose())
}

func renderCompose() string {
	var builder strings.Builder
	builder.WriteString("# Code generated by backend/cmd/render-microservice-compose; DO NOT EDIT.\n")
	builder.WriteString("version: '3.9'\n\n")
	builder.WriteString("x-backend-common: &backend-common\n")
	builder.WriteString("  image: golang:1.25\n")
	builder.WriteString("  working_dir: /app/backend\n")
	builder.WriteString("  volumes:\n")
	builder.WriteString("    - ./:/app\n")
	builder.WriteString("  environment: &backend-env\n")
	builder.WriteString("    APP_ENV: development\n")
	builder.WriteString("    DATABASE_DRIVER: mysql\n")
	builder.WriteString("    DATABASE_DSN: gameadmin:gameadmin@tcp(mysql:3306)/game_admin?charset=utf8mb4&parseTime=True&loc=Local\n")
	builder.WriteString("    REDIS_ENABLED: \"true\"\n")
	builder.WriteString("    REDIS_ADDR: redis:6379\n")
	builder.WriteString("    REDIS_PASSWORD: \"\"\n")
	builder.WriteString("    REDIS_DB: \"0\"\n")
	builder.WriteString("    REDIS_PREFIX: game-admin:\n")
	builder.WriteString("    MQ_ENABLED: \"true\"\n")
	builder.WriteString("    MQ_DRIVER: rabbitmq\n")
	builder.WriteString("    MQ_URL: amqp://guest:guest@rabbitmq:5672/\n")
	builder.WriteString("    MQ_TOPIC: game-admin.events\n")
	builder.WriteString("  depends_on:\n")
	builder.WriteString("    mysql:\n")
	builder.WriteString("      condition: service_healthy\n")
	builder.WriteString("    redis:\n")
	builder.WriteString("      condition: service_started\n")
	builder.WriteString("    rabbitmq:\n")
	builder.WriteString("      condition: service_started\n\n")

	builder.WriteString("services:\n")
	for _, name := range sortedHTTPServiceNames() {
		builder.WriteString(renderMigrateService(name))
	}
	builder.WriteString(renderGatewayService())
	for _, name := range sortedHTTPServiceNames() {
		builder.WriteString(renderHTTPService(name))
	}
	for _, name := range sortedWorkerServiceNames() {
		builder.WriteString(renderWorkerService(name))
	}
	builder.WriteString(renderFrontendService())
	builder.WriteString(renderInfraServices())
	return builder.String()
}

func sortedHTTPServiceNames() []string {
	items := servicedef.HTTPNames()
	slices.Sort(items)
	return items
}

func sortedWorkerServiceNames() []string {
	items := servicedef.WorkerNames()
	slices.Sort(items)
	return items
}

func renderMigrateService(name string) string {
	return fmt.Sprintf("  migrate-%s:\n    <<: *backend-common\n    command: sh -c 'go run ./cmd/migrate-service %s'\n    profiles: [\"migrate\"]\n\n", name, name)
}

func renderGatewayService() string {
	var builder strings.Builder
	builder.WriteString("  gateway:\n")
	builder.WriteString("    <<: *backend-common\n")
	builder.WriteString(fmt.Sprintf("    command: %s\n", renderLoggedCommand("gateway-service", "./cmd/gateway-service")))
	builder.WriteString("    environment:\n")
	builder.WriteString("      <<: *backend-env\n")
	for _, name := range sortedHTTPServiceNames() {
		def := servicedef.MustHTTP(name)
		envKey := gatewayEnvKey(name)
		builder.WriteString(fmt.Sprintf("      GATEWAY_%s_URL: http://%s:%s\n", envKey, name, def.DefaultPort))
	}
	for _, name := range sortedWorkerServiceNames() {
		def := servicedef.MustWorker(name)
		envKey := gatewayEnvKey(name)
		builder.WriteString(fmt.Sprintf("      GATEWAY_%s_URL: http://%s:%s\n", envKey, name, def.DefaultPort))
	}
	builder.WriteString("    ports:\n")
	builder.WriteString("      - \"8080:8080\"\n")
	builder.WriteString("    depends_on:\n")
	for _, name := range sortedHTTPServiceNames() {
		builder.WriteString(fmt.Sprintf("      %s:\n        condition: service_started\n", name))
	}
	for _, name := range sortedWorkerServiceNames() {
		builder.WriteString(fmt.Sprintf("      %s:\n        condition: service_started\n", name))
	}
	builder.WriteString("\n")
	return builder.String()
}

func renderHTTPService(name string) string {
	def := servicedef.MustHTTP(name)
	return fmt.Sprintf("  %s:\n    <<: *backend-common\n    command: %s\n    environment:\n      <<: *backend-env\n      METRICS_PORT: %s\n    ports:\n      - \"%s:%s\"\n\n", name, renderLoggedCommand(name, "./cmd/"+name), def.DefaultPort, def.DefaultPort, def.DefaultPort)
}

func renderWorkerService(name string) string {
	def := servicedef.MustWorker(name)
	return fmt.Sprintf("  %s:\n    <<: *backend-common\n    command: %s\n    environment:\n      <<: *backend-env\n      METRICS_PORT: %s\n    ports:\n      - \"%s:%s\"\n\n", name, renderLoggedCommand(name, "./cmd/"+name), def.DefaultPort, def.DefaultPort, def.DefaultPort)
}

